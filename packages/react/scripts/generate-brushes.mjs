import {readFile, writeFile as writeOutput, mkdir, readdir, unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {readBrush, clipPolygon, svgDocument, roundedBackbone} from './brush-geometry.mjs';

const check = process.argv.includes('--check');
async function writeFile(url, content) {
  if (check) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Stale brush asset: ${url.pathname}. Run pnpm brushes:generate.`);
  } else await writeOutput(url, content);
}

const sourceDirectory = new URL('../brushes/', import.meta.url);
const output = new URL('../src/brush-border/generated/', import.meta.url);
const configText = await readFile(new URL('preset.json', sourceDirectory), 'utf8');
const config = JSON.parse(configText);
const source = await readFile(new URL(config.source, sourceDirectory), 'utf8');
const {polygons, viewBox: [vx, , vw]} = readBrush(source);
if (config.variants !== 6) throw new Error('Update the public BrushVariant union before changing the variant count.');
if (!Number.isFinite(config.centerline) || !(config.sourceThickness > 0) || !(config.thickness > 0) || !Number.isFinite(config.seed)) {
  throw new Error('Brush metadata needs a finite centerline/seed and positive source/target thickness.');
}
for (const preset of Object.values(config.presets)) {
  if (!(preset.slice >= preset.radius && preset.width > 2 * preset.slice && preset.height >= 2 * preset.slice)) {
    throw new Error('Slices must contain the complete radius and fit the canonical rectangle.');
  }
}
if (!check) await mkdir(output, {recursive: true});
// Only remove generator-owned assets; keep this directory safe to regenerate.
if (!check) for (const file of await readdir(output)) if (/^(small|round|circle|line)-\d+(?:-\d+|-vertical)?\.svg$/.test(file)) await unlink(new URL(file, output));
const css = ['/* Generated by pnpm brushes:generate. Do not edit. */'];
const manifest = {source: config.source, hash: createHash('sha256').update(source + configText).digest('hex'), variants: config.variants, presets: config.presets};
for (let variant = 0; variant < config.variants; variant++) {
  const phase = ((config.seed * 0.61803398875 + variant * 0.17320508076) % 1);
  const reverse = variant % 2 ? -1 : 1;
  const flip = variant % 3 === 0 ? -1 : 1;
  const declarations = [];
  function deform(width, height, radius) {
    const backbone = roundedBackbone(width, height, radius, config.thickness * 0.6);
    return polygons.map((polygon) => polygon.map(([x, y]) => {
      const t = (x - vx) / vw;
      const distance = (t * reverse + phase) * backbone.length;
      const [px, py, tx, ty] = backbone.at(distance);
      // Periodic, low-amplitude variation. Width is independent of path length.
      const angle = distance / backbone.length * Math.PI * 2;
      const pressure = 1 + 0.045 * Math.sin(angle * 3 + variant) + 0.025 * Math.cos(angle * 7 + variant);
      const offset = (y - config.centerline) / config.sourceThickness * config.thickness * pressure * flip;
      return [px - ty * offset, py + tx * offset];
    }));
  }
  await writeFile(new URL(`circle-${variant}.svg`, output), svgDocument(deform(16, 16, 8), [0, 0, 16, 16]));
  declarations.push(`  --brush-circle-image: url('./circle-${variant}.svg');`);
  for (const [name, {width, height, radius, slice}] of Object.entries(config.presets)) {
    const deformed = deform(width, height, radius);
    const bounds = [
      [0, 0, slice, slice], [slice, 0, width - slice, slice], [width - slice, 0, width, slice],
      [0, slice, slice, height - slice], [width - slice, slice, width, height - slice],
      [0, height - slice, slice, height], [slice, height - slice, width - slice, height], [width - slice, height - slice, width, height],
    ];
    const images = [];
    for (const [index, [left, top, right, bottom]] of bounds.entries()) {
      // Exact shared clipping planes. A single compound path preserves holes;
      // mask layers meet, rather than overlapping semi-transparent paint.
      const clipped = deformed.map((p) => clipPolygon(p, [left, top, right, bottom]));
      const file = `${name}-${variant}-${index}.svg`;
      await writeFile(new URL(file, output), svgDocument(bottom > top ? clipped : [], [left, top, right - left, Math.max(1, bottom - top)]));
      images.push(`url('./${file}')`);
    }
    declarations.push(`  --brush-${name}-images: ${images.join(', ')};`);
  }
  // One slice: only the longitudinal dimension stretches, never the thickness.
  const line = polygons.map((p) => p.map(([x, y]) => {
    const t = (x - vx) / vw;
    const pressure = 1 + 0.025 * Math.sin(t * Math.PI * 6 + variant);
    return [variant % 2 ? 100 - t * 100 : t * 100, (y - config.centerline) / config.sourceThickness * 10 * flip * pressure + 6];
  }));
  await writeFile(new URL(`line-${variant}.svg`, output), svgDocument(line, [0, 0, 100, 12]));
  await writeFile(new URL(`line-${variant}-vertical.svg`, output), svgDocument(line.map((p) => p.map(([x, y]) => [y, x])), [0, 0, 12, 100]));
  declarations.push(`  --brush-line-image: url('./line-${variant}.svg');`, `  --brush-line-vertical-image: url('./line-${variant}-vertical.svg');`);
  css.push(`:where([data-brush-variant='${variant}']) {\n${declarations.join('\n')}\n}`);
}
await writeFile(new URL('assets.css', output), css.join('\n\n') + '\n');
await writeFile(new URL('manifest.json', output), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Generated ${config.variants} variants × ${Object.keys(config.presets).length} radius presets + one-slice lines.`);
