import {
  forwardRef,
  type ForwardRefExoticComponent,
  type Ref,
  type RefAttributes,
  type SVGProps,
} from 'react';

export interface LogoVariantProps extends Omit<
  SVGProps<SVGSVGElement>,
  'children' | 'height' | 'width'
> {
  /** "auto" follows the page's color-scheme via CSS light-dark(). */
  scheme?: 'auto' | 'light' | 'dark';
  /** Rendered height; the width follows the artwork's aspect ratio. Defaults to 32. */
  height?: number | string;
}

export interface LogoProps extends LogoVariantProps {
  /** Symbol and wordmark lockup. Omit for the symbol alone. */
  lockup?: 'horizontal' | 'vertical';
  /** One-color version, for layouts that require it. */
  monochrome?: boolean;
}

export type LogoVariantComponent = ForwardRefExoticComponent<
  LogoVariantProps & RefAttributes<SVGSVGElement>
>;

export type LogoComponent = ForwardRefExoticComponent<LogoProps & RefAttributes<SVGSVGElement>>;

interface SchemeColor {
  light: string;
  dark: string;
}

interface Artwork {
  width: number;
  height: number;
  paths: Array<{token: string; d: string; fillRule?: 'evenodd'}>;
}

/** One variant's artwork and only the colors it uses, generated by build.ts. */
export interface LogoVariantData {
  colors: Record<string, SchemeColor>;
  artwork: Artwork;
}

export interface LogoData {
  /** Artwork by `lockup` prop; the symbol alone is "logo". */
  kinds: Record<string, {color: LogoVariantData; monochrome: LogoVariantData}>;
}

export function createLogo(displayName: string, brandName: string, data: LogoData): LogoComponent {
  const Logo = forwardRef<SVGSVGElement, LogoProps>(function ElanorLogo(
    {lockup, monochrome = false, ...props},
    ref,
  ) {
    const kind = data.kinds[lockup ?? 'logo'];
    if (!kind) throw new Error(`${displayName} has no ${lockup} lockup`);
    return renderLogo(
      displayName,
      brandName,
      monochrome ? kind.monochrome : kind.color,
      props,
      ref,
    );
  });
  Logo.displayName = displayName;
  return Logo;
}

export function createLogoVariant(
  displayName: string,
  brandName: string,
  data: LogoVariantData,
): LogoVariantComponent {
  const Logo = forwardRef<SVGSVGElement, LogoVariantProps>(function ElanorLogoVariant(props, ref) {
    return renderLogo(displayName, brandName, data, props, ref);
  });
  Logo.displayName = displayName;
  return Logo;
}

function renderLogo(
  displayName: string,
  brandName: string,
  {artwork, colors}: LogoVariantData,
  {scheme = 'auto', height = 32, style, ...props}: LogoVariantProps,
  ref: Ref<SVGSVGElement>,
) {
  const numeric = typeof height === 'number';
  const named =
    props['aria-hidden'] == null ||
    props['aria-hidden'] === false ||
    props['aria-hidden'] === 'false';
  return (
    <svg
      role={named ? 'img' : undefined}
      aria-label={named ? brandName : undefined}
      {...props}
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox={`0 0 ${artwork.width} ${artwork.height}`}
      height={height}
      width={numeric ? (height * artwork.width) / artwork.height : undefined}
      style={
        numeric
          ? style
          : {aspectRatio: `${artwork.width} / ${artwork.height}`, width: 'auto', ...style}
      }
    >
      {artwork.paths.map(({token, d, fillRule}, index) => {
        const color = colors[token];
        if (!color) throw new Error(`${displayName} has no color for ${token}`);
        const auto = scheme === 'auto' && color.light !== color.dark;
        return (
          <path
            key={index}
            d={d}
            fillRule={fillRule}
            fill={auto ? undefined : color[scheme === 'dark' ? 'dark' : 'light']}
            style={auto ? {fill: `light-dark(${color.light}, ${color.dark})`} : undefined}
          />
        );
      })}
    </svg>
  );
}
